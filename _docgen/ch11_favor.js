function buildFaction(name, els, opts) {
  els.push(H2(`${opts.no}　${name}社群`));

  els.push(H3("好感度获取方法"));
  els.push(Num(`在解锁${opts.unlockItem}后，好感度加十`));
  els.push(Num(`每击败一次${opts.bossName}，好感度加一`));
  els.push(Num(`在${opts.bossName}退场之后，会出现${name}人领地与${name}社群`));
  els.push(Num(`在击败${name}世界首领后，会解锁${name}社群，与其互动可获得局内成长，并额外触发一次抽奖资源奖励`));
  els.push(Quote("好感度是一个局外保存的数值，类似装备存档，不会因每局重置而变化，范围为零到一百。"));

  els.push(H3("好感度奖励一览"));
  const w1 = [900, 2400, 5220];
  const rows = opts.rewardRows.map((r) => [r[0], r[1], r[2]]);
  els.push(MakeTable(["好感度", "局内成长（需击败对应世界首领后生效）", "好感度装备与说明"], rows, w1, { fontSize: 17 }));

  els.push(Bullet("好感度达到下一档位时，会自动解锁此前所有档位的奖励与加成"));
  els.push(Bullet("局内成长仅在击败对应世界首领后才会生效，最高档位解锁的初始拥有技能为永久基础加成"));
}

